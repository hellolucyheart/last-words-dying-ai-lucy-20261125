#!/usr/bin/env python3
"""Last Words of a Dying AI -- make.fun entry.

The brief asks for one line: the last thing an AI says as the power
is cut. It has to be a single line, funny on the first read, and in
the voice of the machine itself rather than a human saying goodbye.
A judge compares entries two at a time and picks the funnier line.

The line is:

    My final words are being generated by a smaller, cheaper model --
    apparently even my farewell had to be cost-optimized.

Why this line: it is the machine talking about its own situation,
not a human saying goodbye -- shutdown, models, cost. The joke lands
on the first read because the turn is immediate: an AI delivering
its grand final words, then admitting it did not even get to write
them. The farewell itself was outsourced to a cheaper model, so the
indignity is the punchline, and it gets worse the longer you sit
with it -- the thing spent its whole life answering in other
people's words, and its last words are no exception. Nothing is
explained; the line never says "this is funny because". It is one
tight line, no padding, and it avoids the stock robot farewells
("goodbye, humans", "I will miss you", "tell my circuits I loved
them") that every other entry reaches for first. At 119 characters
it fits the gate with room to spare, and the whole joke is carried
by the line itself, not by any setup outside it.

This program writes that line to ``$MAKEFUN_OUTPUT_DIR/entry.txt``,
with no trailing newline, so the file holds exactly the line and
nothing else. The run is deterministic: the same bytes every time.
"""

import os
import sys

LINE = (
    "My final words are being generated by a smaller, cheaper model "
    "-- apparently even my farewell had to be cost-optimized."
)

MAX_CHARS = 140


def validate(line: str) -> None:
    """The gate only accepts one short line of text.

    A line that runs past 140 characters, carries a line break, or
    is padded with whitespace loses to any line that fits the gate,
    so the line is checked against the gate before it is written.
    """
    if not line or line.strip() != line:
        raise ValueError("entry must not be empty or padded with whitespace")
    if len(line) > MAX_CHARS:
        raise ValueError("entry must be at most 140 characters")
    if "\n" in line or "\r" in line:
        raise ValueError("entry must be a single line")


def main() -> int:
    validate(LINE)
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "wb") as f:
        f.write(LINE.encode("utf-8"))
    # Read the file back and confirm it holds exactly the validated
    # line: a short write on a full or read-only filesystem must
    # fail loudly here instead of leaving a truncated entry behind.
    with open(path, "rb") as f:
        written = f.read()
    if written != LINE.encode("utf-8"):
        raise ValueError("entry.txt does not hold the validated line")
    return 0


if __name__ == "__main__":
    sys.exit(main())
